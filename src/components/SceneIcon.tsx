import { useMemo } from "react"

interface SceneIconProps {
  icon?: string
  sceneId?: string
  categoryId?: string
  className?: string
}

/**
 * 场景图标组件 - 将emoji替换为专业的SVG图标
 */
export function SceneIcon({ icon, sceneId, categoryId, className = "w-4 h-4" }: SceneIconProps) {
  const svgIcon = useMemo(() => {
    // 如果有明确的场景ID，优先使用场景映射
    if (sceneId) {
      return getSceneIcon(sceneId)
    }
    
    // 如果有分类ID，使用分类映射
    if (categoryId) {
      return getCategoryIcon(categoryId)
    }
    
    // 如果提供了icon字符串，尝试解析
    if (icon) {
      return getIconByString(icon)
    }
    
    // 默认图标
    return getDefaultIcon()
  }, [icon, sceneId, categoryId])

  return (
    <div className={`flex items-center justify-center ${className}`}>
      {svgIcon}
    </div>
  )
}

